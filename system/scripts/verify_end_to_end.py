def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--sessions", type=int, default=6,
                        help="synthetic sessions, one teacher each (default 6, the minimum "
                             "that can make three teacher-disjoint partitions)")
    parser.add_argument("--seconds", type=float, default=42.0,
                        help="length of each synthetic session; must clear the real duration "
                             "floor, which is MIN_USEFUL_CLIPS x behaviour.clip.length_s")
    parser.add_argument("--keep", action="store_true",
                        help="leave the scratch database and files in place")
    parser.add_argument("--config", type=Path, default=REPO_ROOT / "configs" / "default.yaml",
                        help="the template to derive the scratch config from")
    args = parser.parse_args(argv)

    template = load_config(args.config)
    ffmpeg = resolve("ffmpeg", template.tools.ffmpeg)
    root = Path(template.paths.scratch) / f"verify-{new_ulid()[-10:].lower()}"
    root.mkdir(parents=True, exist_ok=True)

    print(f"verification run in {root}")
    print("  synthetic corpus, scratch database, nothing real is touched\n")

    dsn = _dsn_from_dev_services()
    scratch_dsn, url = create_database(dsn)
    name = dict(piece.split("=", 1) for piece in scratch_dsn.split())["dbname"]
    print(f"  database   {name} created and migrated")

    started = time.monotonic()
    report: dict[str, object] = {"infrastructure_validation": True, "root": str(root)}
    try:
        manifest, incoming = build_corpus(root, ffmpeg, args.sessions, args.seconds)
        print(f"  corpus     {args.sessions} synthetic sessions in {incoming.name}/")

        keymap = root / "keys.csv"
        config_path = write_config(args.config, root / "config.yaml", root,
                                   manifest=manifest, media_dir=incoming, keymap=keymap)
        env = {**_env(), "DATABASE_URL": url,
               "PRAXIS_MEDIA_ROOT": str((root / "media").resolve())}

        mint = run_script("ingest_corpus.py", "--config", str(config_path),
                          "--manifest", str(manifest), "--media-dir", str(incoming),
                          "--keymap", str(keymap), "--create-missing", "--dry-run", env=env)
        if not keymap.is_file():
            raise VerificationFailed(
                f"identifier minting wrote no key file:\n{mint.stdout}\n{mint.stderr}")
        granted = seed_consents(url, keymap)
        print(f"  consent    {granted} synthetic consent records, marked SYNTHETIC")

        build = subprocess.run(
            [sys.executable, str(REPO_ROOT / "scripts" / "run_build.py"),
             "--config", str(config_path)],
            capture_output=True, text=True, stdin=subprocess.DEVNULL, cwd=REPO_ROOT, env=env)
        sys.stdout.write(build.stdout)
        if build.returncode not in (RAN, ABSTAINED):
            raise VerificationFailed(f"the build failed:\n{build.stderr[-2000:]}")

        phases = phase_results(root / "runs")
        report["phases"] = phases
        report["database"] = check_database(url)
        report["api"] = check_api(url, config_path, root / "media")
        report["audit_chain"] = check_audit_chain(env)
        report["seconds"] = round(time.monotonic() - started, 1)

        (root / "verification.json").write_text(
            json.dumps(report, indent=2, sort_keys=True, default=str) + "\n", encoding="utf-8")
        _print_report(report)
        return RAN

    except VerificationFailed as exc:
        print(f"\nVERIFICATION FAILED: {exc}", file=sys.stderr)
        return FAILED
    finally:
        if args.keep:
            print(f"\nkept: {root} and database {scratch_dsn}")
        else:
            drop_database(dsn, scratch_dsn)
            print("\nscratch database dropped")


def _print_report(report: dict[str, object]) -> None:
    database = report["database"]
    phases = report["phases"]
    ran = [p for p in phases if p["ran"]]

    print("\n" + "=" * 78)
    print("WHAT THE DATABASE HOLDS")
    for name, count in database["counts"].items():
        print(f"  {name:18} {count}")
    print(f"  quality verdicts   {database['quality_verdicts'] or 'none'}")
    print(f"  blurred media      {database['blurred_media']}")

    print("\nWHAT THE API ANSWERED")
    for name, value in report["api"].items():
        print(f"  {name:18} {value}")
    print(f"  audit chain        {report['audit_chain']}")

    print("\nPHASES")
    for phase in sorted(phases, key=lambda p: (len(str(p["phase"])), str(p["phase"]))):
        verdict = "ran" if phase["ran"] else "abstained"
        print(f"  {phase['phase']!s:>4}  {verdict:<9}  "
              f"{phase['artefacts']} artefact(s)")
        if phase["abstained"]:
            print(f"        {phase['abstained'][:88]}")

    print("\n" + "=" * 78)
    print(f"{len(ran)} of {len(phases)} phases ran, {len(phases) - len(ran)} abstained, "
          f"in {report['seconds']}s")
    print("Every figure above is infrastructure validation on generated footage.")
    print("It says the pipeline executes. It says nothing about teaching-behaviour detection.")


if __name__ == "__main__":
    raise SystemExit(main())
