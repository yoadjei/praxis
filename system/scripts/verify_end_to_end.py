# -*- coding: utf-8 -*-
"""Run the whole system on a synthetic corpus, in a scratch database, and report what happened.

    python scripts/verify_end_to_end.py
    python scripts/verify_end_to_end.py --keep          # leave the scratch database behind
    python scripts/verify_end_to_end.py --sessions 4

This exists to answer one question: does the system work end to end on this machine? It builds
a corpus from nothing, puts it through every phase the real corpus would go through, and
prints which phases ran, which abstained and why.

**What it proves and what it does not.** It proves the pipeline executes: that ingest writes
sessions, that the quality gate judges them, that preprocessing extracts pose and destroys the
original, that the audit chain verifies, that the API answers, and that every phase either
does its work or says what it is missing. It proves *nothing* about teaching-behaviour
detection. The clips are generated by ffmpeg and contain no teacher, no learner and no
behaviour, so every artefact this writes is stamped `infrastructure_validation: true`. A
number measured here is a property of the plumbing and may never be reported as a result.

**It touches nothing real.** A fresh database created and dropped per run, a scratch media
root under `paths.scratch`, and a scratch config. The research database, the real corpus and
`configs/default.yaml` are not read for anything but a template and are never written.

Two gate settings are relaxed for synthetic footage, and the report says so: the duration
floor, because generating 40 seconds of video per session to clear a floor about behaviour
episodes wastes minutes to prove nothing, and the person-presence fraction, because `testsrc`
contains no person. Every other check runs as configured. The real corpus is where the gate is
exercised for real.
"""
