# the synthetic corpus
# ---------------------------------------------------------------------------

def make_clip(ffmpeg, path: Path, seconds: float, *, colour: str) -> Path:
    """One clip. `colour` differs per session so no two are byte-identical and deduplicated."""
    path.parent.mkdir(parents=True, exist_ok=True)
    argv = [
        "-y",
        "-f", "lavfi", "-i", f"color=c={colour}:size=640x480:rate=25:duration={seconds}",
        "-f", "lavfi", "-i", f"sine=frequency=440:duration={seconds}",
        "-c:a", "aac", "-c:v", "libx264", "-preset", "ultrafast", "-pix_fmt", "yuv420p",
        str(path),
    ]
    done = subprocess.run(ffmpeg.command("-v", "error", *argv, file_only=False),
                          capture_output=True, text=True, stdin=subprocess.DEVNULL, timeout=300)
    if done.returncode != 0 or not path.is_file():
        raise VerificationFailed(f"ffmpeg could not build {path.name}: {done.stderr.strip()}")
    return path


COLOURS = ("red", "green", "blue", "yellow", "magenta", "cyan", "orange", "purple")


def build_corpus(root: Path, ffmpeg, count: int, seconds: float) -> tuple[Path, Path]:
    """Synthetic footage plus the manifest naming it. One session per teacher."""
    incoming = root / "incoming"
    rows = []
    for index in range(count):
        name = f"session-{index + 1:02d}.mp4"
        make_clip(ffmpeg, incoming / name, seconds, colour=COLOURS[index % len(COLOURS)])
        rows.append(
            f"{name},T-{index + 1:02d},COE-V,microteaching,2026-03-{index + 1:02d},"
            f"science,JHS2,3.5,48,31,52,4.2\n")

    manifest = root / "sessions.csv"
    manifest.write_text(MANIFEST_HEADER + "".join(rows), encoding="utf-8")
    return manifest, incoming


def seed_consents(url: str, keymap: Path) -> int:
    """One live consent per teacher in the key file, so ingest has a basis to proceed.

    The real path for this is `scripts/import_consents.py`, which requires a document reference
    naming a signed form. Here the subjects are synthetic and the reference says so: a
    verification run must not leave a row that could be mistaken for evidence of real consent.
    """
    import csv

    with keymap.open(newline="", encoding="utf-8-sig") as handle:
        pairs = [(row["teacher_code"], row["teacher_id"], row["college_id"])
                 for row in csv.DictReader(handle)]
    if not pairs:
        raise VerificationFailed(f"{keymap} has no teacher rows; identifier minting failed")

    engine = build_engine(url)
    with transaction(engine) as conn:
        for code, teacher_id, college_id in pairs:
            conn.execute(consent_records.insert().values(
                consent_id=new_ulid(), subject_type="teacher", teacher_id=teacher_id,
                college_id=college_id,
                purpose="SYNTHETIC infrastructure verification, not research",
                recipients="nobody; this corpus is generated and contains no person",
                scope="both", granted_on=date(2026, 1, 1),
                document_ref=f"SYNTHETIC/verification/{code}", created_at=func.now()))
    return len(pairs)


