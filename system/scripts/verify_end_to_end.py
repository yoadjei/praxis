def run_script(script: str, *argv: str, env: dict[str, str]) -> subprocess.CompletedProcess:
    return subprocess.run(
        [sys.executable, str(REPO_ROOT / "scripts" / script), *argv],
        capture_output=True, text=True, stdin=subprocess.DEVNULL, cwd=REPO_ROOT, env=env)


def phase_results(run_outputs: Path) -> list[dict[str, object]]:
    """Every run under `run_outputs`, newest first, with its verdict."""
    found = []
    for directory in sorted(run_outputs.iterdir(), reverse=True):
        manifest, result = directory / "manifest.json", directory / "result.json"
        if not (directory.is_dir() and manifest.is_file() and result.is_file()):
            continue
        man = json.loads(manifest.read_text(encoding="utf-8"))
        res = json.loads(result.read_text(encoding="utf-8"))
        found.append({
            "phase": man.get("phase"), "run_id": man.get("run_id"),
            "ran": bool(res.get("ran")),
            "abstained": (res.get("abstained") or {}).get("reason"),
            "missing": (res.get("abstained") or {}).get("missing") or [],
            "artefacts": len(man.get("artefacts") or []),
            "summary": {k: v for k, v in res.items()
                        if k not in ("ran", "abstained", "artefacts")},
        })
    return found


def check_database(url: str) -> dict[str, object]:
    """What actually landed. These are the assertions, not a progress report."""
    engine = build_engine(url)
    with transaction(engine) as conn:
        counts = {
            name: conn.execute(select(func.count()).select_from(table)).scalar_one()
            for name, table in (("colleges", colleges), ("teachers", teachers),
                                ("consent_records", consent_records), ("sessions", sessions),
                                ("media_objects", media_objects),
                                ("pose_artifacts", pose_artifacts))
        }
        verdicts = dict(conn.execute(
            select(sessions.c.quality_verdict, func.count())
            .group_by(sessions.c.quality_verdict)).all())
        blurred = conn.execute(
            select(func.count()).select_from(media_objects)
            .where(media_objects.c.is_blurred.is_(True))).scalar_one()
    return {"counts": counts, "quality_verdicts": verdicts, "blurred_media": blurred}


def check_api(url: str, config_path: Path, media_root: Path) -> dict[str, object]:
    """The API answers against this corpus. Built through the factory, not the entry point."""
    from fastapi.testclient import TestClient

    from praxis.api.app import create_app

    app = create_app(config=load_config(config_path), engine=build_engine(url),
                     media_root=media_root, enqueue=lambda _session_id: None)
    client = TestClient(app)
    answers = {}
    for name, path in (("health", "/api/v1/health"),
                       ("summary", "/api/v1/dashboard/summary"),
                       ("sessions", "/api/v1/dashboard/sessions?limit=50")):
        response = client.get(path)
        answers[name] = response.status_code
        if response.status_code != 200:
            raise VerificationFailed(f"{path} answered {response.status_code}: {response.text}")
        if name == "sessions":
            answers["sessions_listed"] = len(response.json().get("sessions", []))
    return answers


def check_audit_chain(env: dict[str, str]) -> str:
    """The hash chain verifies. R5's whole point, checked by the script that owns it.

    `--from-db` and not a JSON export, because the chain this build wrote is in the scratch
    database and nothing has exported it. The argument was missing entirely until now, so the
    verifier exited 2 on its own usage message and the harness read that as a broken chain:
    every run of this script ended in "VERIFICATION FAILED: the audit chain does not verify"
    with the eleven phases underneath it reporting no failures at all. The chain was never
    checked, and the one check that would have said so was the one that could not run.
    """
    done = run_script("verify_audit_chain.py", "--from-db", env=env)
    if done.returncode != 0:
        raise VerificationFailed(
            f"the audit chain does not verify:\n{done.stdout}\n{done.stderr}")
    return reported_head(done.stdout)


def reported_head(stdout: str) -> str:
    """The head hash the verifier printed, or a statement that there is no head.

    This took the last line of stdout, which is the head only when the chain has rows in it. An
    empty chain prints one line - "empty. An empty chain is intact and proves nothing." - and
    that sentence went into the report's `audit_chain` field, under a heading that reads "audit
    chain" and alongside a hash in every other run. A field that holds a hash most of the time
    and a sentence the rest of the time is one a reader will quote as a hash.

    An empty chain is not a failure: the verifier exits 0 and is right to, and D48 makes an
    unavailable check abstain rather than fail. What it must not do is look like a verified
    head. So it is named as what it is.
    """
    for line in stdout.strip().splitlines():
        if line.startswith(HEAD_PREFIX):
            return line
    return "no head: the audit log is empty, which is intact and proves nothing"


