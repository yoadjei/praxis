RAN, FAILED, ABSTAINED = 0, 1, 3
MANIFEST_HEADER = ("filename,teacher_code,college_code,domain,recorded_on,subject,grade_level,"
                   "camera_distance_m,room_area_m2,pupil_count,ambient_noise_dba,"
                   "teacher_movement_range_m\n")


class VerificationFailed(RuntimeError):
    """A step that had to work did not. Distinct from a phase that abstained."""


# ---------------------------------------------------------------------------
# the scratch environment
# ---------------------------------------------------------------------------

def _admin_dsn(dsn: str) -> str:
    return re.sub(r"dbname=\S+", "dbname=postgres", dsn)


def _dsn_from_dev_services() -> str:
    """The local cluster's DSN, via the script that already knows how to print it."""
    done = subprocess.run(
        [sys.executable, str(REPO_ROOT / "scripts" / "dev_services.py"), "dsn"],
        capture_output=True, text=True, stdin=subprocess.DEVNULL)
    if done.returncode != 0:
        raise VerificationFailed(
            f"could not get a database DSN: {done.stderr.strip() or done.stdout.strip()}. "
            f"Start the cluster with: python scripts/dev_services.py start")
    match = re.search(r'export PRAXIS_TEST_DSN="([^"]+)"', done.stdout)
    if not match:
        raise VerificationFailed(
            f"dev_services.py dsn printed something unexpected: {done.stdout}")
    return match.group(1)


def create_database(dsn: str) -> tuple[str, str]:
    """A fresh database, migrated. Returns its keyword DSN and its SQLAlchemy URL."""
    import psycopg

    name = f"praxis_verify_{new_ulid()[-12:].lower()}"
    scratch = re.sub(r"dbname=\S+", f"dbname={name}", dsn)
    parts = dict(piece.split("=", 1) for piece in scratch.split())
    url = (f"postgresql+psycopg://{parts['user']}:{parts['password']}"
           f"@{parts['host']}:{parts['port']}/{name}")

    with psycopg.connect(_admin_dsn(dsn), autocommit=True) as conn:
        conn.execute(f'CREATE DATABASE "{name}"')

    applied = subprocess.run(
        [sys.executable, "-m", "alembic", "upgrade", "head"], cwd=REPO_ROOT,
        capture_output=True, text=True, stdin=subprocess.DEVNULL, timeout=300,
        env={**_env(), "DATABASE_URL": url})
    if applied.returncode != 0:
        raise VerificationFailed(f"could not migrate {name}:\n{applied.stderr}")
    return scratch, url


def drop_database(dsn: str, scratch: str) -> None:
    import psycopg

    name = dict(piece.split("=", 1) for piece in scratch.split())["dbname"]
    with psycopg.connect(_admin_dsn(dsn), autocommit=True) as conn:
        conn.execute("SELECT pg_terminate_backend(pid) FROM pg_stat_activity "
                     "WHERE datname = %s AND pid <> pg_backend_pid()", (name,))
        conn.execute(f'DROP DATABASE IF EXISTS "{name}"')


def _env() -> dict[str, str]:
    import os
    return dict(os.environ)


def write_config(template: Path, destination: Path, root: Path, *,
                 manifest: Path, media_dir: Path, keymap: Path) -> Path:
    """A scratch config: the real one with every path pointed inside `root`.

    Read as raw YAML and not through `load_config`, because the template carries `${VAR}`
    placeholders that must be replaced with literal scratch paths rather than resolved from an
    environment this run does not control.
    """
    raw = yaml.safe_load(template.read_text(encoding="utf-8"))

    def as_posix(path: Path) -> str:
        return path.resolve().as_posix()

    raw["paths"].update({
        "media_root": as_posix(root / "media"),
        "feature_cache": as_posix(root / "features"),
        "pose_artifacts": as_posix(root / "pose"),
        "run_outputs": as_posix(root / "runs"),
        "scratch": as_posix(root / "tmp"),
        "torch_home": as_posix(root / "torch"),
    })
    raw["ingest"].update({
        "manifest": as_posix(manifest),
        "media_dir": as_posix(media_dir),
        "keymap": as_posix(keymap),
    })
    # One relaxation, and it is reported as one. `testsrc` contains no person, so the presence
    # fraction is the single check synthetic footage cannot pass. The duration floor is NOT
    # lowered: `the_duration_floor_admits_enough_clips` refuses a floor under five clips, and it
    # is right to, so the clips are generated long enough to clear it for real.
    raw["ingest"]["quality_gate"]["min_person_present_fraction"] = 0.0
    raw["run"]["name"] = "verification"

    for key in ("media", "features", "pose", "runs", "tmp", "torch"):
        (root / key).mkdir(parents=True, exist_ok=True)
    destination.write_text(yaml.safe_dump(raw, sort_keys=False), encoding="utf-8")
    return destination


