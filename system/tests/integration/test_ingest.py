def mixed_rate_clip(path: Path, fast_fps: int, slow_fps: int, half: float) -> Path:
    """One stream carrying two frame rates, which is what a phone recording is.

    `r_frame_rate` becomes the least common multiple of the two and overstates the file;
    `avg_frame_rate` is the frame count over the duration and describes it.
    """
    argv = ["-y",
            "-f", "lavfi", "-i", f"testsrc=size={WIDTH}x{HEIGHT}:rate={fast_fps}:d={half}",
            "-f", "lavfi", "-i", f"testsrc=size={WIDTH}x{HEIGHT}:rate={slow_fps}:d={half}",
            "-filter_complex", "[0:v][1:v]concat=n=2:v=1[out]", "-map", "[out]",
            "-fps_mode", "vfr",
            "-c:v", "libx264", "-preset", "ultrafast", "-pix_fmt", "yuv420p", str(path)]
    done = subprocess.run(FFMPEG.command("-v", "error", *argv, file_only=False),
                          capture_output=True, text=True, stdin=subprocess.DEVNULL, timeout=600)
    assert done.returncode == 0, f"could not generate a fixture: {done.stderr[:400]}"
    return path


def test_the_frame_rate_is_what_the_file_delivers_not_what_its_timebase_allows(
        tmp_path) -> None:
    """Half at 30 fps and half at 10 is a 20 fps recording. `r_frame_rate` calls it 30, which is
    above the configured floor, so the check used to pass a file it exists to refuse. D79."""
    clip = mixed_rate_clip(tmp_path / "mixed.mp4", fast_fps=30, slow_fps=10, half=3.0)
    metadata = probe_module.probe(FFPROBE, clip)

    assert metadata.fps == pytest.approx(20.0, abs=0.5)
    assert metadata.fps < CONFIG.ingest.quality_gate.min_fps


def test_a_recording_too_choppy_for_the_gate_is_refused(tmp_path) -> None:
    """The check and the number it reads, together. Duration is lowered so this fails on the
    frame rate and nothing else."""
    clip = mixed_rate_clip(tmp_path / "choppy.mp4", fast_fps=30, slow_fps=10, half=3.0)
    gate = lenient().ingest.quality_gate

    metadata = probe_module.probe(FFPROBE, clip)
    report = probe_report(metadata, gate, clip)

    assert report.verdict == "fail"
    assert any(c.name == "frame_rate" for c in report.failures), report.reason()


def probe_report(metadata, gate, clip: Path):
    from praxis.ingest.quality import evaluate

    return evaluate(metadata, gate,
                    fps_jitter=probe_module.frame_rate_jitter(FFPROBE, clip),
                    mean_luma=mean_luminance(FFMPEG, clip, gate.person_detection_sample_frames,
                                             metadata.duration_s),
                    person_fraction=None)


def test_a_steady_recording_reports_the_rate_it_was_made_at(tmp_path) -> None:
    """The fallback must not cost accuracy on ordinary constant-rate footage."""
    metadata = probe_module.probe(FFPROBE, make_clip(tmp_path / "steady.mp4", 4.0))
    assert metadata.fps == pytest.approx(float(FPS), abs=0.3)


# ---------------------------------------------------------------------------
# Brightness sampling
#
# The gate's luminance check reads frames from across the file. These tests are about *which*
# frames it reaches, because a sampler that silently only ever read the opening seconds would
# still return a plausible number for every clip above.
# ---------------------------------------------------------------------------

def two_tone_clip(path: Path, seconds: float) -> Path:
    """Black for the first half, white for the second. Its mean luminance is near the middle.

    A clip whose brightness is uniform cannot distinguish a sampler that spans the file from one
    that reads the first frame N times, and that is the distinction being tested.
    """
    half = seconds / 2
    argv = ["-y",
            "-f", "lavfi", "-i", f"color=c=black:size={WIDTH}x{HEIGHT}:rate={FPS}:d={half}",
            "-f", "lavfi", "-i", f"color=c=white:size={WIDTH}x{HEIGHT}:rate={FPS}:d={half}",
            "-filter_complex", "[0:v][1:v]concat=n=2:v=1[out]", "-map", "[out]",
            "-c:v", "libx264", "-preset", "ultrafast", "-pix_fmt", "yuv420p", str(path)]
    done = subprocess.run(FFMPEG.command("-v", "error", *argv, file_only=False),
                          capture_output=True, text=True, stdin=subprocess.DEVNULL, timeout=600)
    assert done.returncode == 0, f"could not generate a fixture: {done.stderr[:400]}"
    return path


def test_brightness_is_sampled_across_the_file_not_from_its_opening(tmp_path) -> None:
    """The measurement is the mean over frames spread through the recording. Half black and half
    white therefore reads mid-grey; a sampler stuck at the start would read near zero."""
    clip = two_tone_clip(tmp_path / "two_tone.mp4", 8.0)
    observed = mean_luminance(FFMPEG, clip, sample_frames=24, duration_s=8.0)
    assert 96 < observed < 160, f"mean luminance {observed} is not mid-scale"


def test_brightness_does_not_depend_on_how_long_the_recording_is(tmp_path) -> None:
    """The same content at two lengths is the same brightness. This is what changed when the
    sampler stopped decoding the whole file and started seeking: the measurement had to stay
    put while the mechanism moved. D78."""
    short = mean_luminance(FFMPEG, two_tone_clip(tmp_path / "short.mp4", 4.0),
                           sample_frames=24, duration_s=4.0)
    longer = mean_luminance(FFMPEG, two_tone_clip(tmp_path / "long.mp4", 20.0),
                            sample_frames=24, duration_s=20.0)
    assert abs(short - longer) < 12


def test_a_black_clip_and_a_white_clip_are_told_apart(tmp_path, clips) -> None:
    white = make_clip(tmp_path / "white.mp4", 4.0,
                      luma=f"color=c=white:size={WIDTH}x{HEIGHT}:rate={FPS}")
    dark = mean_luminance(FFMPEG, clips["dark"], sample_frames=12, duration_s=6.0)
    bright = mean_luminance(FFMPEG, white, sample_frames=12, duration_s=4.0)
    assert dark < 32 < 224 < bright


def test_a_sampling_timeout_is_a_refusal_rather_than_a_subprocess_error(tmp_path,
                                                                       monkeypatch) -> None:
    """Every ffmpeg call in this module goes through `_run` so that a timeout becomes an
    `IngestRefused` the service can record. The brightness sampler used to call
    `subprocess.run` itself, so a long recording ended the ingest request with a raw
    `TimeoutExpired` and nothing in the audit trail said why. D78."""
    clip = make_clip(tmp_path / "plain.mp4", 2.0)

    def always_times_out(*args, **kwargs):
        raise subprocess.TimeoutExpired(cmd="ffmpeg", timeout=1)

    monkeypatch.setattr(probe_module.subprocess, "run", always_times_out)

    with pytest.raises(IngestRefused, match="could not be read within"):
        mean_luminance(FFMPEG, clip, sample_frames=4, duration_s=2.0)


def test_an_undecodable_sample_point_is_skipped_but_a_whole_bad_file_is_refused(clips) -> None:
    """A seek landing in a damaged region contributes nothing and the remaining samples still
    produce a measurement. A file with no decodable frame anywhere is a refusal."""
    with pytest.raises(IngestRefused, match="brightness"):
        mean_luminance(FFMPEG, clips["corrupt"], sample_frames=4, duration_s=6.0)

    # zero samples requested is not a failure to decode; it is nothing asked for
    assert mean_luminance(FFMPEG, clips["good"], sample_frames=0, duration_s=6.0) == 0.0
    assert mean_luminance(FFMPEG, clips["good"], sample_frames=4, duration_s=0.0) == 0.0


