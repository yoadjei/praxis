def test_acceptance_a_clip_below_the_duration_floor_fails_and_one_above_passes(
        engine, party, media_root, tmp_path) -> None:
    """The one test that uses the real configured thresholds, since they are what it checks.

    BUILD-SPEC phrased this as "three minutes fails and twenty passes", which was the 300-second
    floor written into the assertion. That floor is now derived from the clip length and stands
    at 40 seconds (D81), and a test naming the old number would have gone on passing while
    describing a gate that no longer exists. The durations come from the configuration instead,
    so this keeps testing the floor rather than a particular value of it.

    The frame size is the smallest the resolution check accepts, which keeps the encode cheap
    while still clearing the gate the duration check is being isolated from.
    """
    if not requires_database(engine):
        return

    floor = CONFIG.ingest.quality_gate.min_duration_s
    cheap = {"with_audio": False, "size": "512x288", "rate": 2}
    short = make_clip(tmp_path / "under.mp4", max(1.0, floor - 10.0), **cheap)
    long_enough = make_clip(tmp_path / "over.mp4", floor + 60.0, **cheap)

    under = run(request_for(short, party), engine, media_root, config=CONFIG)
    over = run(request_for(long_enough, party, recorded_on=date(2026, 5, 6)),
               engine, media_root, config=CONFIG)

    assert under.quality.as_detail()["duration"]["verdict"] == "fail"
    assert under.quality.verdict == "fail"
    assert over.quality.as_detail()["duration"]["verdict"] == "pass"
    assert over.quality.as_detail()["resolution"]["verdict"] == "pass", (
        "the fixture must clear the resolution gate, or this is not isolating duration")


# ---------------------------------------------------------------------------
# Geometry under rotation
#
# Half the real corpus is portrait phone video and two files carry a -90 display matrix. The
# decoder applies that rotation; what the record must not do is describe the stream instead of
# the frames the pipeline will see. D80, D81.
# ---------------------------------------------------------------------------

def rotated_clip(path: Path, seconds: float, degrees: int) -> Path:
    """A clip carrying a display matrix, written the way a phone writes one.

    Two steps because `-display_rotation` is an input option: encode plainly, then remux with
    the rotation applied and the stream copied, which is what a container with a rotated
    display matrix and unrotated pixels actually looks like.
    """
    plain = path.with_name(f"plain-{path.name}")
    make_clip(plain, seconds, with_audio=False, size="640x360", rate=5)
    done = subprocess.run(
        FFMPEG.command("-v", "error", "-y", "-display_rotation", str(degrees),
                       "-i", str(plain), "-c", "copy", str(path), file_only=False),
        capture_output=True, text=True, stdin=subprocess.DEVNULL, timeout=600)
    assert done.returncode == 0, f"could not rotate a fixture: {done.stderr[:400]}"
    return path


@pytest.mark.parametrize("degrees", [90, 270])
def test_the_recorded_geometry_is_what_the_decoder_produces(tmp_path, degrees) -> None:
    """A quarter turn swaps the axes. Recording 640x360 for a file that decodes to 360x640
    would describe a landscape recording that does not exist, and the resolution check would
    then be testing the wrong edge. D80."""
    import cv2

    clip = rotated_clip(tmp_path / f"r{degrees}.mp4", 2.0, degrees)
    metadata = probe_module.probe(FFPROBE, clip)

    capture = cv2.VideoCapture(str(clip))
    ok, frame = capture.read()
    capture.release()
    assert ok

    assert metadata.rotation_degrees == degrees
    assert (metadata.width, metadata.height) == (frame.shape[1], frame.shape[0])
    assert metadata.is_portrait and metadata.orientation == "portrait"


def test_an_unrotated_recording_is_unaffected(tmp_path) -> None:
    metadata = probe_module.probe(FFPROBE, make_clip(tmp_path / "flat.mp4", 2.0))
    assert metadata.rotation_degrees == 0
    assert metadata.orientation == "landscape"
    assert (metadata.width, metadata.height) == (WIDTH, HEIGHT)


def test_portrait_and_landscape_of_the_same_size_are_judged_alike(tmp_path) -> None:
    """D81. The gate measures frame area and shorter edge, not width and height. 360x640 and
    640x360 hold the same amount of teacher and letterbox into the same square, so a width
    threshold would accept one and refuse the other for no reason that survives stating."""
    gate = CONFIG.ingest.quality_gate
    landscape = probe_module.probe(FFPROBE, make_clip(tmp_path / "land.mp4", 2.0,
                                                      with_audio=False, size="640x360", rate=5))
    portrait = probe_module.probe(FFPROBE, rotated_clip(tmp_path / "port.mp4", 2.0, 90))

    assert landscape.pixels == portrait.pixels
    assert landscape.shorter_edge == portrait.shorter_edge

    def accepted(m) -> bool:
        return m.pixels >= gate.min_frame_pixels and m.shorter_edge >= gate.min_shorter_edge

    assert accepted(landscape) == accepted(portrait)


def test_a_frame_too_small_to_pose_is_still_refused(tmp_path) -> None:
    """Relaxing the resolution gate for portrait footage must not relax it into nothing."""
    gate = CONFIG.ingest.quality_gate
    tiny = probe_module.probe(FFPROBE, make_clip(tmp_path / "tiny.mp4", 2.0, with_audio=False,
                                                 size="160x120", rate=5))
    assert tiny.pixels < gate.min_frame_pixels
    assert tiny.shorter_edge < gate.min_shorter_edge


def test_a_wide_strip_is_refused_on_its_shorter_edge(tmp_path) -> None:
    """Area alone is not enough. A very wide, very short frame can clear the pixel floor while
    leaving a standing teacher a few dozen pixels tall once letterboxed into the pose square."""
    gate = CONFIG.ingest.quality_gate
    strip = probe_module.probe(FFPROBE, make_clip(tmp_path / "strip.mp4", 2.0, with_audio=False,
                                                  size="1920x96", rate=5))
    assert strip.pixels >= gate.min_frame_pixels, "the fixture must clear the area floor"
    assert strip.shorter_edge < gate.min_shorter_edge, "and be refused on its shorter edge"
