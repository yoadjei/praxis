def test_acceptance_upload_without_valid_consent_stores_no_bytes_and_no_rows(
        engine, party, clips, media_root) -> None:
    if not requires_database(engine):
        return

    before = (rows(engine, sessions), rows(engine, media_objects))
    with pytest.raises(IngestRefused) as refused:
        run(request_for(clips["good"], party, consent_id=new_ulid()), engine, media_root)

    assert refused.value.refusal.status == 422
    assert refused.value.refusal.slug == "consent-invalid"
    assert (rows(engine, sessions), rows(engine, media_objects)) == before
    assert list(media_root.rglob("*.mp4")) == [], "R: a refused upload wrote bytes"
    assert list((media_root / TEMP_SUBDIR).glob("*.part")) == []

    # The refusal is still in the trail; that is what an audit is for.
    with transaction(engine) as conn:
        rejected = conn.execute(select(func.count()).select_from(audit_log).where(
            audit_log.c.event_type == "session.rejected")).scalar()
    assert rejected >= 1


def test_acceptance_the_same_file_twice_deduplicates_to_one_media_object(
        engine, party, clips, media_root) -> None:
    """One media object, two sessions permitted - the second under a different date, since the
    same file for the same teacher on the same day is a duplicate click. D51."""
    if not requires_database(engine):
        return

    first = run(request_for(clips["good"], party), engine, media_root)
    second = run(request_for(clips["good"], party, recorded_on=date(2026, 5, 5)),
                 engine, media_root)

    assert first.media.media_sha256 == second.media.media_sha256
    assert second.media.deduplicated and not first.media.deduplicated
    assert first.session.session_id != second.session.session_id

    # Counted by hash rather than by table, because the scratch database is shared across the
    # module and a global count would be asserting about the other tests.
    digest = first.media.media_sha256
    mine = (sessions.c.media_sha256 == digest) & (sessions.c.teacher_id == party["teacher_id"])
    assert rows(engine, media_objects, media_objects.c.media_sha256 == digest) == 1
    assert rows(engine, sessions, mine) == 2
    assert len(list((media_root / "media").rglob("*.mp4"))) == 1


def test_acceptance_a_duplicate_upload_is_refused(engine, party, clips, media_root) -> None:
    """Same hash, same teacher, same date. Refused by the constraint, not by a prior SELECT,
    because check-then-insert is a race. D51."""
    if not requires_database(engine):
        return

    first = run(request_for(clips["good"], party), engine, media_root)
    with pytest.raises(IngestRefused) as refused:
        run(request_for(clips["good"], party), engine, media_root)

    assert refused.value.refusal.status == 409
    assert rows(engine, sessions,
                (sessions.c.media_sha256 == first.media.media_sha256)
                & (sessions.c.teacher_id == party["teacher_id"])) == 1


def test_acceptance_a_corrupt_mp4_fails_with_a_reason_not_a_stack_trace(
        engine, party, clips, media_root) -> None:
    if not requires_database(engine):
        return

    before = (rows(engine, sessions), rows(engine, media_objects))
