def test_a_good_upload_becomes_a_session(engine, party, clips, media_root) -> None:
    if not requires_database(engine):
        return

    queue = RecordingQueue()
    result = run(request_for(clips["good"], party), engine, media_root, queue=queue)

    assert result.quality.verdict in ("pass", "warn")
    assert result.session.media_sha256 == result.media.media_sha256
    assert result.media.absolute(media_root).is_file()
    assert queue.delivered == [result.session.session_id], (
        "the queue is handed the session id, once, after the commit")

    with transaction(engine) as conn:
        stored = conn.execute(select(sessions).where(
            sessions.c.session_id == result.session.session_id)).mappings().one()
    assert stored["quality_verdict"] == result.quality.verdict
    assert set(stored["quality_detail"]) == {c.name for c in result.quality.checks}


def test_the_session_and_its_audit_row_commit_together(engine, party, clips,
                                                      media_root) -> None:
    """D47. The trail and the facts cannot disagree, so they are one transaction."""
    if not requires_database(engine):
        return

    result = run(request_for(clips["good"], party), engine, media_root)
    with transaction(engine) as conn:
        chain = read_chain(conn)
        ingested = [r for r in chain if r.entity_id == result.session.session_id]

    assert len(ingested) == 1
    assert ingested[0].event_type == "session.ingested"
    assert ingested[0].payload["teacher_id"] == party["teacher_id"]
    assert ingested[0].row_hash == result.audit_row_hash
    assert verify(chain) is None


