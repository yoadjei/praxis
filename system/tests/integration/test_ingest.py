"""Phase 1 end to end, against a real database and real video.

The fixtures are generated by ffmpeg rather than committed, and their properties are read back
from the file rather than assumed. A fixture written to match the implementation would prove
only that the code agrees with itself, which is how this project has twice shipped a defect that
every local reading made look correct.

The four acceptance tests BUILD-SPEC names for this phase are at the bottom, marked.

Video generation is slow, so the clips are session-scoped and the gate thresholds are lowered
for the tests that do not care about duration. The duration thresholds themselves are exercised
against the real configured values, because that is the check being tested.
"""
