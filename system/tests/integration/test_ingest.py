@pytest.fixture(scope="session")
def clips(tmp_path_factory) -> dict[str, Path]:
    root = tmp_path_factory.mktemp("clips")
    return {
        "good": make_clip(root / "good.mp4", 6.0),
        "silent": make_clip(root / "silent.mp4", 6.0, with_audio=False),
        "dark": make_clip(root / "dark.mp4", 6.0,
                          luma="color=c=black:size=1280x720:rate=25"),
        "corrupt": _corrupt(root / "corrupt.mp4"),
    }


def _corrupt(path: Path) -> Path:
    """Not a video. ffprobe must refuse it with a reason rather than a traceback.

    Plain ASCII with no container header rather than random bytes: the point is that
    ffprobe can find no format at all, and a deterministic payload means a failure here
    is always the same failure.
    """
    path.write_bytes(b"this file claims to be an mp4 and is not" * 512)
    return path


def request_for(clip: Path, party: dict, **overrides) -> IngestRequest:
    base = dict(
        filename=clip.name, chunks=read_in_chunks(clip, CONFIG.ingest.hash_chunk_bytes),
        teacher_id=party["teacher_id"], college_id=party["college_id"],
        consent_id=party["consent_id"], domain="classroom", school_id=party["school_id"],
        recorded_on=date(2026, 5, 4),
        subject="integrated science", actor_role="researcher")
    base.update(overrides)
    return IngestRequest(**base)


def run(request, engine, media_root, config=None, queue=None):
    return ingest(request, engine=engine, config=config or lenient(),
                  ffprobe=FFPROBE, ffmpeg=FFMPEG, media_root=media_root,
                  enqueue=queue or RecordingQueue())


def rows(engine, table, where=None) -> int:
    statement = select(func.count()).select_from(table)
    if where is not None:
        statement = statement.where(where)
    with transaction(engine) as conn:
        return conn.execute(statement).scalar()


