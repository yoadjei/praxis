@pytest.fixture
def party(engine):
    """A college, a school, a teacher and a live consent, so the foreign keys resolve.

    The school is here because a classroom session cannot be written without one -
    `a_classroom_session_names_its_school`, D98 - and most of these tests ingest classroom
    footage. A microteaching test simply passes `school_id=None` and the constraint allows it.
    """
    if engine is None:
        return None
    college, teacher, consent = new_ulid(), new_ulid(), new_ulid()
    school = new_ulid()
    with transaction(engine) as conn:
        conn.execute(colleges.insert().values(
            college_id=college, code=f"COL-{college[-5:]}", created_at=func.now()))
        conn.execute(schools.insert().values(
            school_id=school, code=f"SCH-{school[-5:]}", created_at=func.now()))
        conn.execute(teachers.insert().values(
            teacher_id=teacher, college_id=college, created_at=func.now()))
        conn.execute(consent_records.insert().values(
            consent_id=consent, subject_type="teacher", teacher_id=teacher,
            college_id=college, purpose="research", recipients="supervisors", scope="both",
            granted_on=date(2025, 1, 1), document_ref="file/1", created_at=func.now()))
    return {"college_id": college, "teacher_id": teacher, "consent_id": consent,
            "school_id": school}
