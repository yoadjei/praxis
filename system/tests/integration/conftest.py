def requires_database(*resources: object) -> bool:
    """Whether a test needing a database can run. The single place that decides.

    `tests/conftest.py` already makes a *configured but unreachable* database a hard failure, so
    what reaches here is genuinely "none configured". D48: such a check abstains, and the
    abstention is its own verdict - hence a warning rather than a silent pass.

    Neither `pytest.skip` nor a bare `return` is used. The project forbids skip, and a bare
    return makes "this test did not run" and "this test passed" look identical, which is the
    failure mode R1 to R7 exist to prevent. One gate rather than one per call site, because
    seventy guards spelling out the same rule is how sixty-nine of them keep it and one drifts
    (L20). CI supplies a database, so in CI this never fires and the tests genuinely run.
    """
    if all(resource is not None for resource in resources):
        return True
    warnings.warn(
        "this test needs a database and none is configured, so it asserted nothing. Start the "
        "development cluster with: python scripts/dev_services.py start",
        stacklevel=2)
    return False

# 720p so the resolution check passes; duration is set per clip.
WIDTH, HEIGHT, FPS = 1280, 720, 25


def make_clip(path: Path, seconds: float, *, with_audio: bool = True,
              luma: str | None = None, size: str | None = None, rate: int = FPS) -> Path:
    """A synthetic clip whose properties the gate reads back off the file itself.

    `size` and `rate` exist so the duration tests can produce a 20-minute file without encoding
    30,000 frames of 720p. They check the container's duration, which is unaffected.
    """
    path.parent.mkdir(parents=True, exist_ok=True)
    source = luma or f"testsrc=size={size or f'{WIDTH}x{HEIGHT}'}:rate={rate}"
    argv = ["-y", "-f", "lavfi", "-i", f"{source}:duration={seconds}"]
    if with_audio:
        argv += ["-f", "lavfi", "-i", f"sine=frequency=440:duration={seconds}", "-c:a", "aac"]
    argv += ["-c:v", "libx264", "-preset", "ultrafast", "-pix_fmt", "yuv420p", str(path)]

    done = subprocess.run(FFMPEG.command("-v", "error", *argv, file_only=False),
                          capture_output=True, text=True, stdin=subprocess.DEVNULL, timeout=600)
    assert done.returncode == 0, f"could not generate a fixture: {done.stderr[:400]}"
    return path


def lenient(seconds_floor: float = 1.0):
    """The real config with the duration floor lowered, for tests about the other checks."""
    gate = CONFIG.ingest.quality_gate.model_copy(update={"min_duration_s": seconds_floor})
    return CONFIG.model_copy(update={
        "ingest": CONFIG.ingest.model_copy(update={"quality_gate": gate})})


