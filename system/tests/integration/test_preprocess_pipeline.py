def test_two_runs_of_one_configuration_produce_the_same_artefact(paths, config,
                                                                 setup) -> None:
    """R7, end to end. Same video, same configuration, same bytes - so the hash in
    `pose_artifacts` identifies the preprocessing, not the occasion it was run on."""
    first = preprocess(paths, config, ScriptedEstimator(), setup)
    second = preprocess(paths, config, ScriptedEstimator(), setup)

    assert second.artifact.sha256 == first.artifact.sha256
    assert second.artifact.config_sha256 == first.artifact.config_sha256
    assert second.frames_processed == first.frames_processed
    assert second.proposal.track_id == first.proposal.track_id



def test_the_artefact_holds_every_sampled_frame_and_verifies(paths, config, setup) -> None:
    result = preprocess(paths, config, ScriptedEstimator(), setup)
    artifact = result.artifact

    assert artifact.frame_count == result.frames_processed
    assert artifact.max_persons == 3
    assert artifact.model_version == "scripted-double-v1"

    loaded = artifacts.load(paths["pose"], artifact.sha256)
    assert loaded.keypoints.shape == (artifact.frame_count, 3, KEYPOINT_COUNT, 3)
    assert loaded.provenance["config_sha256"] == artifact.config_sha256
    assert set(loaded.person_count.tolist()) == {3}


def test_the_teacher_track_is_proposed_and_left_unconfirmed(paths, config, setup) -> None:
    """The scripted teacher is present throughout, largest, and in the front zone, so the
    heuristic should name that track. It still may not confirm it."""
    result = preprocess(paths, config, ScriptedEstimator(), setup)
    proposal = result.proposal

    assert proposal.track_id is not None
    assert not proposal.is_confirmed
    row = proposal.as_row(source="detection", limit=20)
    assert row["confirmed_by"] is None
    # The ranking the reviewer is shown reaches the row, which before 0009 it did not.
    assert row["reason"] == proposal.reason
    assert [c["track_id"] for c in row["candidates"]["ranked"]] == [
        s.track_id for s in proposal.signals]

    keypoints = teacher_keypoints(paths["pose"], proposal.track_id, result.artifact.sha256)
    assert keypoints.shape == (result.artifact.frame_count, KEYPOINT_COUNT, 3)

    # The proposed track is the physically largest one, which is what the weights encode.
    ranked = sorted(proposal.signals, key=lambda s: s.median_area_fraction, reverse=True)
    assert ranked[0].track_id == proposal.track_id


def test_learner_bins_count_the_learners_and_not_the_teacher(paths, config, setup) -> None:
    result = preprocess(paths, config, ScriptedEstimator(), setup, learner_bin_seconds=10.0)

    assert result.learner_bins, "a two-second session still produces one bin"
    total = result.learner_bins[0]
    assert total.person_count == 2, "two seated learners; the proposed teacher is excluded"
    assert total.hands_raised == 1, "one learner raises one hand, once"


def test_a_learner_bin_reaches_the_database_row_without_an_identifier(paths, config,
                                                                     setup) -> None:
    """R1 at the boundary: what `summarise` hands to the writer has no column for a person."""
    result = preprocess(paths, config, ScriptedEstimator(), setup)
    row = result.learner_bins[0].as_row("01" + "0" * 24)

    assert set(row) == {"session_id", "t_start_s", "hands_raised", "gross_motion",
                        "person_count"}


def test_an_empty_room_produces_an_artefact_and_no_proposal(paths, config, setup) -> None:
    """Nothing detected is a real outcome. It must not crash, and it must not propose a
    teacher out of an empty frame."""
    result = preprocess(paths, config, BlindEstimator(), setup)

    assert result.frames_processed > 0
    assert result.faces_blurred == 0
    assert result.proposal.track_id is None
    assert result.learner_bins[0].person_count == 0
    assert not paths["source"].exists(), "the original still goes, whatever was in it"

    loaded = artifacts.load(paths["pose"], result.artifact.sha256)
    assert loaded.keypoints.shape[1] == 0
    assert set(loaded.person_count.tolist()) == {0}


def test_a_session_without_zones_still_runs_and_says_so(paths, config) -> None:
    """An unmarked setup weakens the heuristic and must say so rather than score as if the
    front-zone term had been measured and found to be zero."""
    result = preprocess(paths, config, ScriptedEstimator(), None)

    assert not result.zones_available
    assert "not comparable" in result.proposal.reason
    # Excluding the teacher is by identity, not by zone, so it survives having no zones.
    assert result.learner_bins[0].person_count == 2


