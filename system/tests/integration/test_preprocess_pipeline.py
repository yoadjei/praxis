def test_a_pose_failure_is_raised_and_the_original_is_kept(paths, config, setup) -> None:
    """A failure before deletion is recoverable; the session can be reprocessed. That is why
    deletion is last."""
    make_clip(paths["source"], 1.0)

    with pytest.raises(FrameProcessingFailed, match="pose estimation failed"):
        run(session_id="01" + "0" * 24, source=paths["source"],
            blurred_destination=paths["blurred"], pose_output=paths["pose"],
            estimator=BrokenEstimator(), config=config, setup=setup)

    assert paths["source"].is_file(), "nothing was deleted, so nothing was lost"


def test_an_undecodable_file_is_refused_before_anything_is_deleted(paths, config,
                                                                   setup) -> None:
    paths["source"].parent.mkdir(parents=True, exist_ok=True)
    paths["source"].write_bytes(b"this is not an mp4")

    with pytest.raises(PreprocessError):
        run(session_id="01" + "0" * 24, source=paths["source"],
            blurred_destination=paths["blurred"], pose_output=paths["pose"],
            estimator=ScriptedEstimator(), config=config, setup=setup)

    assert paths["source"].is_file()
