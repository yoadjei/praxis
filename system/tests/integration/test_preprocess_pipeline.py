# -*- coding: utf-8 -*-
"""The Phase 3 pipeline end to end, on a real video file.

The video is generated by ffmpeg and decoded by the code under test; the estimator is a test
double. That split is deliberate. Everything the pipeline decides - what to sample, what to
blur, what order to do it in, what to delete - is exercised against real decoding, while the
one component that needs vendored weights is substituted by something whose output is known
exactly. A pose model on a `testsrc` pattern would detect nothing, so a test that used the real
one would assert on an empty pipeline and prove nothing about any of it.

What this therefore does NOT establish: whether YOLOv8-pose finds the people in a Ghanaian
basic-school classroom, or whether the teacher heuristic picks the right person there. Both
need the corpus, and the second needs a human regardless - `require_human_confirmation: true`.
"""
from __future__ import annotations

from pathlib import Path

import numpy as np
import pytest

from praxis.preprocess import artifacts
from praxis.preprocess.pipeline import (
    FrameProcessingFailed,
    PreprocessError,
    VideoUnreadable,
    run,
    sample_step,
    teacher_keypoints,
)
from praxis.preprocess.pose import KEYPOINT_COUNT, Detection
from praxis.preprocess.zones import CameraSetup, Polygon
from tests.integration.conftest import FPS, HEIGHT, WIDTH, make_clip

NOSE, LEFT_EYE, RIGHT_EYE = 0, 1, 2
LEFT_SHOULDER, RIGHT_SHOULDER = 5, 6
LEFT_WRIST, RIGHT_WRIST = 9, 10

assert (WIDTH, HEIGHT) == (1280, 720), "the scripted geometry below is in pixels of this clip"

TEACHER_WIDTH, TEACHER_HEIGHT = 140, 400        # near the camera, at the front
LEARNER_WIDTH, LEARNER_HEIGHT = 60, 150         # further away, seated
WALK_PERIOD, WALK_STEP = 16, 30                 # samples per lap, pixels per sample


def _keypoints(x: float, y: float, w: float, h: float, *, hand_up: bool) -> np.ndarray:
    keypoints = np.zeros((KEYPOINT_COUNT, 3), dtype=np.float32)
    cx = x + w / 2
    keypoints[NOSE] = (cx, y + h * 0.08, 0.9)
    keypoints[LEFT_EYE] = (cx - w * 0.12, y + h * 0.06, 0.9)
    keypoints[RIGHT_EYE] = (cx + w * 0.12, y + h * 0.06, 0.9)

    shoulder_y = y + h * 0.25
    keypoints[LEFT_SHOULDER] = (cx - w * 0.3, shoulder_y, 0.9)
    keypoints[RIGHT_SHOULDER] = (cx + w * 0.3, shoulder_y, 0.9)
    keypoints[LEFT_WRIST] = (cx - w * 0.35,
                             shoulder_y - h * 0.15 if hand_up else shoulder_y + h * 0.35, 0.9)
    keypoints[RIGHT_WRIST] = (cx + w * 0.35, shoulder_y + h * 0.35, 0.9)
    return keypoints


class ScriptedEstimator:
    """A `PoseEstimator` whose output is written down rather than inferred.

    One large person walking across the front of the room and two small seated ones, the first
    of whom raises a hand partway through. Which track the heuristic should propose is therefore
    known, which is what makes the assertion about it meaningful.
    """

    model_version = "scripted-double-v1"

    def __init__(self) -> None:
        self.calls = 0

    def detect(self, frame: np.ndarray) -> list[Detection]:
        index = self.calls
        self.calls += 1

        # A triangle wave, so the teacher turns around rather than teleporting back to the
        # start. A modulo wrap would move the box further in one sample than its own width, the
        # tracker would correctly refuse to match it, and the track would fragment - which would
        # be the fixture testing its own arithmetic rather than the pipeline.
        phase = index % WALK_PERIOD
        offset = phase if phase <= WALK_PERIOD // 2 else WALK_PERIOD - phase
        walking_x = 200 + offset * WALK_STEP
        teacher = Detection(
            bbox=(walking_x, 140, walking_x + TEACHER_WIDTH, 140 + TEACHER_HEIGHT),
            keypoints=_keypoints(walking_x, 140, TEACHER_WIDTH, TEACHER_HEIGHT, hand_up=False),
            confidence=0.93)

        learners = []
        for seat, (x, y) in enumerate(((500, 520), (800, 520))):
            hand_up = seat == 0 and index >= 4
            learners.append(Detection(
                bbox=(x, y, x + LEARNER_WIDTH, y + LEARNER_HEIGHT),
                keypoints=_keypoints(x, y, LEARNER_WIDTH, LEARNER_HEIGHT, hand_up=hand_up),
                confidence=0.81))
        return [teacher, *learners]


class BlindEstimator:
    """Detects nothing, which is a legitimate outcome and must not be a crash."""

    model_version = "blind-double-v1"

    def detect(self, frame: np.ndarray) -> list[Detection]:
        return []


class BrokenEstimator:
    model_version = "broken-double-v1"

    def detect(self, frame: np.ndarray) -> list[Detection]:
        raise RuntimeError("the model refused this frame")


def band(top: float, bottom: float) -> Polygon:
    return Polygon(((0.0, top), (1.0, top), (1.0, bottom), (0.0, bottom)))


@pytest.fixture
def setup() -> CameraSetup:
    """Front band covers the teacher's walking line; learners sit in middle and back."""
    return CameraSetup(
        setup_id="01" + "0" * 24, zone_board=band(0.0, 0.15), zone_front=band(0.15, 0.7),
        zone_middle=band(0.7, 0.85), zone_back=band(0.85, 1.0),
        learner_region=band(0.7, 1.0))


@pytest.fixture
def paths(tmp_path: Path) -> dict[str, Path]:
    return {"source": tmp_path / "incoming" / "session.mp4",
            "blurred": tmp_path / "media" / "session.blurred.mp4",
            "pose": tmp_path / "pose" / "session.npz"}


SYNTHETIC_SESSION = "01" + "0" * 24


def preprocess(paths, config, estimator, setup, seconds: float = 2.0,
               session_id: str = SYNTHETIC_SESSION, **kwargs):
    make_clip(paths["source"], seconds)
    return run(session_id=session_id, source=paths["source"],
               blurred_destination=paths["blurred"], pose_output=paths["pose"],
               estimator=estimator, config=config, setup=setup, **kwargs)


