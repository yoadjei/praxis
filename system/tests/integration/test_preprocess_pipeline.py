def test_the_original_does_not_survive_preprocessing(paths, config, setup) -> None:
    """The deletion BUILD-SPEC calls non-negotiable, verified against the filesystem."""
    result = preprocess(paths, config, ScriptedEstimator(), setup)

    assert not paths["source"].exists()
    assert result.original_deleted
    assert paths["blurred"].is_file() and paths["blurred"].stat().st_size > 0


def test_pose_runs_before_the_faces_are_destroyed(paths, config, setup) -> None:
    """The order is the whole design: the estimator must see every sampled frame, and the
    blurred output must be a different file from the one it saw."""
    estimator = ScriptedEstimator()
    result = preprocess(paths, config, estimator, setup)

    assert estimator.calls == result.frames_processed > 0
    assert result.faces_blurred > 0
    assert paths["blurred"].resolve() != paths["source"].resolve()


def test_every_decoded_frame_is_written_to_the_blurred_video(paths, config, setup) -> None:
    """Sampling controls what pose sees, not what survives. A blurred video shorter than the
    original would be a different recording of the lesson."""
    import cv2

    seconds = 2.0
    make_clip(paths["source"], seconds)
    capture = cv2.VideoCapture(str(paths["source"]))
    original_frames = int(capture.get(cv2.CAP_PROP_FRAME_COUNT))
    capture.release()

    run(session_id="01" + "0" * 24, source=paths["source"],
        blurred_destination=paths["blurred"], pose_output=paths["pose"],
        estimator=ScriptedEstimator(), config=config, setup=setup)

    capture = cv2.VideoCapture(str(paths["blurred"]))
    written = int(capture.get(cv2.CAP_PROP_FRAME_COUNT))
    capture.release()

    assert written == original_frames


def test_the_sampling_rate_is_the_configured_one(paths, config, setup) -> None:
    result = preprocess(paths, config, ScriptedEstimator(), setup, seconds=2.0)

    assert result.artifact.sampled_fps == config.preprocess.sample_fps
    expected = int(2.0 * FPS / sample_step(FPS, config.preprocess.sample_fps))
    assert abs(result.frames_processed - expected) <= 1


def test_sampling_is_deterministic() -> None:
    """R7. The step depends only on the two rates, so two runs of the same configuration select
    the same frames."""
    assert sample_step(25.0, 8.0) == pytest.approx(3.125)
    assert sample_step(8.0, 8.0) == 1.0
    assert sample_step(4.0, 8.0) == 1.0, "never invent frames the source does not have"
    with pytest.raises(VideoUnreadable):
        sample_step(0.0, 8.0)


